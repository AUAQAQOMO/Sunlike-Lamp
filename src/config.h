#pragma once
#include <Arduino.h>

// ============================================================================
// 1. 引脚定义（对应原理图 V1.0 / LED DRIVER / Board1）
// ============================================================================
#define PIN_PWM_WARM   0    // GPIO0 -> 网络 PWM3000K -> U4(LGS63042EP) EN 引脚
#define PIN_PWM_COOL   1    // GPIO1 -> 网络 PWM5700K -> U5(LGS63042EP) EN 引脚
#define PIN_EC11_A     6    // GPIO6 -> EC11 PORT A
#define PIN_EC11_B     4    // GPIO4 -> EC11 PORT B
#define PIN_EC11_KEY   5    // GPIO5 -> EC11 BUTTON（低电平有效）

// ============================================================================
// 2. PWM 参数
//    LEDC 时钟源固定为 XTAL 40MHz（模组内部 40MHz 晶振）：
//      f = 40MHz / (div * 2^res) = 40e6 / (1.953125 * 1024) = 20000.0 Hz
//    div = 1.953125 可被 LEDC 的 8 位小数分频器精确表示，故频率无误差。
//    若实测输出电容有可闻啸叫，把 PWM_FREQ_HZ 提到 22000~25000 即可
//    （芯片支持 100Hz~100kHz）。
// ============================================================================
#define PWM_FREQ_HZ    20000
#define PWM_RES_BITS   10
#define PWM_DUTY_MAX   1023                 // 2^10 - 1

// ============================================================================
// 3. 电流与功率
//    LGS63042: I_out(avg) = 0.2V / R_sense * 占空比
//    -> 300mR 时满占空比输出 666.7mA（手册 0.195~0.205V => 650~683mA）
//    两路平均电流之和恒等于“单路满电流”，对应 36V x 0.667A ≈ 24W 输出。
// ============================================================================
#define R_SENSE_MILLIOHM    300
#define LED_CURRENT_MAX_MA  667

// 最低可用占空比：20kHz 下 1 个 duty 只有 48.8ns 高电平，EN 引脚来不及响应。
// 实测若最暗一档不亮/闪烁，把这个值调大（8 => 390ns）；若响应良好可试 5。
// 注意：这里只约束“总占空比”。极暗 + 中间色温时，较小那一路的占空比可能低到
// 2~4 级；若实测暗端偏色，请同时抬高这个值与 BRIGHT_MIN。
#define DUTY_MIN_USABLE     8

// ============================================================================
// 4. 调光曲线与步进
// ============================================================================
#define GAMMA_VALUE     2.2f        // 感知亮度 -> 平均电流的 gamma
#define BRIGHT_MIN      0.02f       // 最暗可用亮度（2%），低于此值驱动不可靠
#define STEP_BRIGHT     0.01f       // 每格亮度步进（1%），暗端会自动放大
#define STEP_CCT        0.02f       // 每格色温步进（2%，共 50 档）
#define MAX_STEP_TRIES  40          // 自适应步进的最大尝试次数（防死循环）

// ============================================================================
// 5. 交互时间参数
// ============================================================================
#define KEY_DEBOUNCE_MS     25      // 按键消抖
#define CLICK_MAX_MS        600     // 按下时间小于此值且未旋转 -> 单击（开关灯）
#define LONGPRESS_MS        5000    // 长按 5s -> 闪烁提示 + 重置配网
#define ENC_TICKS_PER_DETENT 4      // EC11 一个机械格 = 4 个正交边沿
#define ENC_DIR             (+1)    // 若顺时针变成调暗，改成 -1

// ============================================================================
// 6. 渐变（LEDC 硬件 fade）
// ============================================================================
// 渐变由 LightEngine 在主循环里插值实现（每 TWEEN_TICK_MS 写一次占空比）。
// 之所以不用 LEDC 硬件 fade：ledc_set_fade_with_time 用整数 scale（每周期最多变 1 级），
// 20kHz/10bit 下满量程最快也要 51ms，秒级过渡物理上做不到（会被压缩掉）。
#define TWEEN_TICK_MS       16      // 插值刷新周期（约 60Hz，平滑且开销极小）

// 开关灯：更缓和的过渡（参考 desktop_smart_lamp 的 2000ms 量级）
#define FADE_MS_ON          1500    // 开灯渐变时长（同时覆盖 LGS63042 内部软启动）
#define FADE_MS_OFF         2000    // 关灯渐变时长

// 调节（亮度/色温）：按占空比变化距离自适应，保证旋钮跟手
#define FADE_MS_PER_DUTY    12      // 每级占空比对应的渐变时间（ms）
#define FADE_MS_MIN         25      // 单次渐变时长下限
#define FADE_MS_MAX         400     // 单次渐变时长上限

// ============================================================================
// 7. 记忆与上报
// ============================================================================
#define PERSIST_DELAY_MS    2000    // 停止操作 2s 后写 NVS，保护 Flash
#define REPORT_MIN_INTERVAL 300     // 向米家/点灯回传状态的最小间隔

// ============================================================================
// 8. 点灯科技 / OTA
//    BLINKER_AUTH_KEY：在点灯 App 里创建设备后复制过来的 key。
//    留空则固件进入“纯本地模式”（不连 WiFi，旋钮照常可用）。
// ============================================================================
#define BLINKER_AUTH_KEY    ""      // TODO: 填入你的点灯科技 AuthKey
#define OTA_HOSTNAME        "sunlike-lamp"
#define OTA_PASSWORD        "sunlike2026"   // 可自行修改

// 可选：不用点灯/米家，但仍想用 OTA 时，填写这里让设备直连固定 WiFi。
// 留空则完全不启动 WiFi（纯本地，最省电、最稳）。
// 说明：OTA 依赖 WiFi，而 WiFi 要么由 blinker 管理，要么在这里写死，
//       所以 AuthKey 为空时必须填这里才能用 OTA。
#define LOCAL_WIFI_SSID     ""
#define LOCAL_WIFI_PASSWORD ""

// ============================================================================
// 9. 色温范围
//    米家侧按开尔文下发，固件内部换算成 0~1 的比例驱动两路混合。
//    米家滑块通常按 2700~6500K 显示，超出物理范围的部分会被两端钳位。
// ============================================================================
#define CCT_WARM_K  3000
#define CCT_COOL_K  5700
