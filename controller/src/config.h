#pragma once
#include <Arduino.h>

// 固件版本（打印在启动横幅，便于确认 OTA/重刷是否生效）
#define FW_VERSION      "1.0.0"

// ============================================================================
// 1. 引脚定义（无线旋钮控制器 V1.0）
//    注意与台灯本体的定义不同：台灯是 A=GPIO6 / B=GPIO4 / KEY=GPIO5。
// ============================================================================
#define PIN_EC11_A     5    // GPIO5 -> EC11 A 相
#define PIN_EC11_B     6    // GPIO6 -> EC11 B 相
#define PIN_EC11_KEY   4    // GPIO4 -> EC11 按键（低电平有效）

// ============================================================================
// 2. 交互参数（与台灯本体保持一致的手感）
// ============================================================================
#define KEY_DEBOUNCE_MS      25
#define CLICK_MAX_MS         600     // 按下短于此值且未旋转 -> 单击（开关）
#define LONGPRESS_MS         5000    // 长按 5s -> 清除配对并重启
#define ENC_TICKS_PER_DETENT 4       // EC11 一格 = 4 个正交边沿
// A/B 引脚与台灯正好互换，若发现顺时针变成调暗/调暖，把这里改成 -1
#define ENC_DIR              (+1)

// ============================================================================
// 3. ESP-NOW 通信与配对
// ============================================================================
#define ESPNOW_SCAN_START_CH      1     // 扫描起始信道
#define ESPNOW_SCAN_END_CH        13    // 扫描结束信道（中国区 1-13）
#define ESPNOW_SCAN_DWELL_MS      800   // 每个信道驻留时间
#define ESPNOW_CMD_MIN_INTERVAL_MS 25   // 命令最小发送间隔（期间的增量会合并）
#define ESPNOW_PING_INTERVAL_MS   30000 // 在线探测周期
#define ESPNOW_PING_TIMEOUT_MS    1500  // 探测应答超时
#define ESPNOW_PING_FAIL_LIMIT    2     // 连续失败几次后开始重扫信道
#define ESPNOW_DELTA_LIMIT        100   // 单次发送的增量上限（防止越界）

// ============================================================================
// 4. 休眠
//    C3 的 deep sleep ext1 只支持 ALL_LOW / ANY_HIGH，而 EC11 是“上拉、
//    动作拉低”，无法用深睡做任意引脚唤醒，所以这里用 light sleep：
//    任意引脚低电平即可唤醒，唤醒约 1ms，WiFi/ESP-NOW 状态由协议栈自动恢复。
// ============================================================================
#define SLEEP_IDLE_MS       60000UL     // 无操作 60s 后进入 light sleep
#define SLEEP_CHECK_MS      1000UL      // 休眠检查周期

// ============================================================================
// 5. NVS
// ============================================================================
#define NVS_NS        "lampctrl"
#define NVS_KEY_MAC   "peer"
#define NVS_KEY_CH    "ch"
